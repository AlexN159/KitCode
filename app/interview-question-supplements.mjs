/** Additional static interview questions used to bring each newer bank to 100. */

function createSupplement(specifications) {
  return Object.freeze(
    specifications.map(
      ([topic, difficulty, question, correctAnswer, distractors, explanation], index) => {
        const correctIndex = (index * 3 + 1) % 4;
        const options = [...distractors];
        options.splice(correctIndex, 0, correctAnswer);
        return Object.freeze({
          topic,
          difficulty,
          question,
          options: Object.freeze(options),
          correctIndex,
          explanation,
        });
      },
    ),
  );
}

